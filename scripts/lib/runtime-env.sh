  local mode="$1"
  local operator_env="$2"
  local -a compose_args
  local resolved_env
  local stage_dir
  local staged_path

  if [[ ! -f "$operator_env" ]]; then
    printf 'Environment file does not exist: %s\n' "$operator_env" >&2
    return 1
  fi

  case "$mode" in
    dev)
      compose_args=(
        -f "$RUNTIME_ENV_ROOT_DIR/infra/compose/docker-compose.base.yml"
        -f "$RUNTIME_ENV_ROOT_DIR/infra/compose/docker-compose.dev.yml"
      )
      ;;
    prod)
      compose_args=(
        -f "$RUNTIME_ENV_ROOT_DIR/infra/compose/docker-compose.base.yml"
        -f "$RUNTIME_ENV_ROOT_DIR/infra/compose/docker-compose.prod.yml"
      )
      ;;
    test)
      compose_args=(-f "$RUNTIME_ENV_ROOT_DIR/infra/compose/docker-compose.test.yml")
      ;;
    *)
      printf 'Unsupported runtime environment: %s\n' "$mode" >&2
      return 1
      ;;
  esac

  umask 077
  mkdir -p "$RUNTIME_ENV_GENERATED_DIR"
  chmod 700 "$RUNTIME_ENV_GENERATED_DIR"
  stage_dir="$(mktemp -d "$RUNTIME_ENV_GENERATED_DIR/.$mode.tmp.XXXXXX")"
  resolved_env="$stage_dir/resolved.env"

  if ! (
    set -euo pipefail
    docker compose --env-file "$operator_env" "${compose_args[@]}" config --environment >"$resolved_env"
    chmod 600 "$resolved_env"

    write_database_projections "$mode" "$resolved_env" "$stage_dir"
    if [[ "$mode" == "test" ]]; then
      write_test_migration_projections "$resolved_env" "$stage_dir"
    else
      write_logto_projections "$mode" "$resolved_env" "$stage_dir"
      write_application_projections "$mode" "$resolved_env" "$stage_dir"
    fi

    if [[ "$mode" == "prod" ]]; then
      local ca_source
      ca_source="$(read_runtime_env_value "$resolved_env" KNOWLEDGE_LOGTO_EXTRA_CA_CERT_PATH || true)"
      if [[ -n "$ca_source" && ! -f "$ca_source" ]]; then
        printf 'Logto CA certificate does not exist: %s\n' "$ca_source" >&2
        exit 1
      fi
      if [[ -n "$ca_source" ]]; then
        cp "$ca_source" "$stage_dir/.env.prod.logto-extra-ca.crt"
      else
        : >"$stage_dir/.env.prod.logto-extra-ca.crt"
      fi
      chmod 600 "$stage_dir/.env.prod.logto-extra-ca.crt"
      write_runtime_projection \
        "$resolved_env" \
        "$stage_dir/.env.prod.cloudflare-ingress.runtime" \
        "TUNNEL_TOKEN=CLOUDFLARE_TUNNEL_TOKEN"
    fi
  ); then
    rm -rf "$stage_dir"
    return 1
  fi

  rm -f "$resolved_env"
  for staged_path in "$stage_dir"/.env."$mode".*; do
    [[ -f "$staged_path" ]] || continue
    mv -f "$staged_path" "$RUNTIME_ENV_GENERATED_DIR/"
  done
  rmdir "$stage_dir"
}
