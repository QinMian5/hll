#!/usr/bin/env bash
# abstract: Materialize service-scoped container environment files from operator configuration.
# out_of_scope: Secret creation, container lifecycle execution, and application-level defaults.

set -euo pipefail

RUNTIME_ENV_ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
RUNTIME_ENV_GENERATED_DIR="$RUNTIME_ENV_ROOT_DIR/infra/env/generated"

runtime_env_value_may_be_empty() {
  case "$1" in
    KNOWLEDGE_LOGTO_DATABASE_STATEMENT_TIMEOUT | \
      KNOWLEDGE_LOGTO_EXTRA_CA_CERT_PATH | \
      KNOWLEDGE_WEB_COOKIE_DOMAIN | \
      KNOWLEDGE_WEB_LOGTO_INTERNAL_ENDPOINT)
      return 0
      ;;
    *)
      return 1
      ;;
  esac
}

read_runtime_env_value() {
  local resolved_env="$1"
  local name="$2"

  awk -v name="$name" '
    index($0, name "=") == 1 {
      print substr($0, length(name) + 2)
      found = 1
      exit
    }
    END {
      if (!found) {
        exit 1
      }
    }
  ' "$resolved_env"
}

require_runtime_env_value() {
  local resolved_env="$1"
  local name="$2"
  local value

  if ! value="$(read_runtime_env_value "$resolved_env" "$name")"; then
    printf 'Missing required runtime environment variable: %s\n' "$name" >&2
    return 1
  fi
  if [[ -z "$value" ]] && ! runtime_env_value_may_be_empty "$name"; then
    printf 'Missing required runtime environment variable: %s\n' "$name" >&2
    return 1
  fi

  printf '%s' "$value"
}

write_runtime_projection() {
  local resolved_env="$1"
  local output_file="$2"
  shift 2

  local mapping
  local source_name
  local target_name
  local value

  {
    printf '# Generated by scripts/lib/runtime-env.sh. Do not edit.\n'
    for mapping in "$@"; do
      if [[ "$mapping" == *=* ]]; then
        target_name="${mapping%%=*}"
        source_name="${mapping#*=}"
      else
        target_name="$mapping"
        source_name="$mapping"
      fi
      value="$(require_runtime_env_value "$resolved_env" "$source_name")"
      printf '%s=%s\n' "$target_name" "$value"
    done
  } >"$output_file"
  chmod 600 "$output_file"
}

append_derived_runtime_value() {
  local resolved_env="$1"
  local name="$2"
  local value="$3"

  printf '%s=%s\n' "$name" "$value" >>"$resolved_env"
}

runtime_database_url() {
  local resolved_env="$1"
  local scheme="$2"
  local user_name="$3"
  local password_name="$4"
  local host="$5"
  local database_name="$6"
  local user
  local password
  local database

  user="$(require_runtime_env_value "$resolved_env" "$user_name")"
  password="$(require_runtime_env_value "$resolved_env" "$password_name")"
  database="$(require_runtime_env_value "$resolved_env" "$database_name")"
  printf '%s://%s:%s@%s:5432/%s' "$scheme" "$user" "$password" "$host" "$database"
}

